#!/usr/bin/env bash
# MiniRedis vs Redis 7.4 (spec 18). Both run in Compose with the same persistence settings
# (AOF everysec, no save points), and redis-benchmark runs inside the redis container against
# both, so neither side gets a networking advantage.
#
#   bash bench/run.sh              # throughput tables, then memory, restart and replica lag
#   ONLY=throughput bash bench/run.sh
#   N=50000 bash bench/run.sh      # a quick run with fewer requests
#
# Writes bench/{redis,miniredis}{,-p16}.csv and bench/tables.md; RESULTS.md quotes the tables.
set -euo pipefail
cd "$(dirname "$0")/.."

N=${N:-200000}
C=${C:-50}
ONLY=${ONLY:-all}
T=ping_inline,ping_mbulk,set,get,incr,lpush,rpush,lpop,rpop,sadd,hset,spop,zadd,zpopmin,lrange_100,mset
OUT=bench/tables.md

section() { [[ $ONLY == all || $ONLY == "$1" ]]; }

docker compose up -d --build --wait miniredis redis

{
  echo "# Benchmark tables"
  echo
  echo "Generated by \`bench/run.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC')."
  echo
  echo "- CPU: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2 | xargs), $(nproc) cores"
  echo "- RAM: $(free -h | awk '/^Mem:/ {print $2}'), OS: $(uname -sr)"
  echo "- Docker $(docker version --format '{{.Server.Version}}'), Node in image: $(docker compose exec -T miniredis node --version)"
  echo "- Redis $(docker compose exec -T redis redis-server --version | grep -o 'v=[0-9.]*' | cut -d= -f2)"
  echo "- \`redis-benchmark -n $N -c $C -t $T --csv\`"
  echo
} > "$OUT"

if section throughput; then
  for P in 1 16; do
    suffix=$([[ $P == 1 ]] && echo "" || echo "-p$P")
    for target in "redis 6379" "miniredis 6380"; do
      set -- $target
      echo ">> $1, -P $P" >&2
      docker compose exec -T redis redis-cli -h "$1" -p "$2" FLUSHALL > /dev/null
      docker compose exec -T redis redis-benchmark -h "$1" -p "$2" \
        -n "$N" -c "$C" -P "$P" -t "$T" --csv > "bench/$1$suffix.csv"
    done
    {
      echo "## Throughput, -P $P"
      echo
      npx tsx bench/report.ts "bench/redis$suffix.csv" "bench/miniredis$suffix.csv"
      echo
    } >> "$OUT"
  done
fi

if section memory; then
  { echo "## Memory, 1M keys with 100-byte values"; echo; npx tsx bench/memory.ts; echo; } >> "$OUT"
fi

if section restart; then
  npm run build > /dev/null
  { echo "## Restart time"; echo; npx tsx bench/restart.ts; echo; } >> "$OUT"
fi

if section lag; then
  docker compose --profile replication up -d --build --wait
  { echo "## Replica lag under load"; echo; npx tsx bench/repl-lag.ts; echo; } >> "$OUT"
  docker compose --profile replication stop replica1 replica2 > /dev/null
fi

echo "Wrote $OUT" >&2
